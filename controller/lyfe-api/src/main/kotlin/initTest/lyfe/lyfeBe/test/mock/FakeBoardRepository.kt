package initTest.lyfe.lyfeBe.test.mock

import lyfe.lyfeBe.board.Board
import lyfe.lyfeBe.board.BoardType
import lyfe.lyfeBe.board.port.out.BoardPort
import org.springframework.data.domain.Pageable
import java.time.LocalDate
import java.util.*
import java.util.concurrent.atomic.AtomicLong

class FakeBoardRepository : BoardPort {

    private val autoGeneratedId = AtomicLong(0)
    private val table: MutableList<Board> = Collections.synchronizedList(ArrayList())

    override fun getById(id: Long) = table.find { it.id == id }!!

    override fun create(board: Board): Board {
        return if (board.id == 0L) {
            val newBoard = board.copy(id = autoGeneratedId.incrementAndGet())
            table.add(newBoard)
            newBoard
        } else {
            table.removeIf { it.id == board.id }
            table.add(board)
            board
        }
    }

    override fun update(board: Board): Board {
        val index = table.indexOfFirst { it.id == board.id }
        if (index != -1) {
            table[index] = board
        }
        return board
    }

    override fun getBoardsWithCursorAndUser(
        cursorId: Long,
        type: BoardType,
        userId: Long,
        pageable: Pageable
    ): List<Board> {
        // 필터링: userId, boardType, cursorId 조건을 만족하는 Board 객체들을 선택
        val boards = table.filter {
            it.user.id == userId &&
                    it.boardType == type &&
                    it.id < cursorId
        }.sortedByDescending { it.id } // 내림차순 정렬

        // 페이징 처리
        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(boards.size)

        return if (offset < boards.size) boards.subList(offset, toIndex) else emptyList()
    }

    override fun findBoardWithCursorAndTopic(
        cursorId: Long,
        type: BoardType,
        topicId: Long?,
        pageable: Pageable
    ): List<Board> {
        val boards = table.filter {
            it.boardType == type &&
                    (topicId == null || it.topic.id == topicId) &&
                    it.id < cursorId
        }.sortedByDescending { it.id }

        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(boards.size)

        return if (offset < boards.size) boards.subList(offset, toIndex) else emptyList()
    }

    override fun findPopularBoardsWithWhisky(
        cursorId: Long,
        topicId: Long,
        type: BoardType,
        pageable: Pageable
    ): List<Board> {
        // whiskyCount 기준으로 내림차순 정렬
        val boards = table.filter {
            it.boardType == type &&
                    it.topic.id == topicId &&
                    it.id < cursorId
        }.sortedWith(compareByDescending<Board> { it.whiskyCount }.thenByDescending { it.id })

        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(boards.size)

        return if (offset < boards.size) boards.subList(offset, toIndex) else emptyList()
    }


    override fun findPopularBoardsWithComment(
        cursorId: Long,
        topicId: Long,
        type: BoardType,
        pageable: Pageable
    ): List<Board> {
        val boards = table.filter {
            it.boardType == type &&
                    it.topic.id == topicId &&
                    it.id < cursorId
        }.sortedByDescending { it.commentCount }

        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(boards.size)

        return if (offset < boards.size) boards.subList(offset, toIndex) else emptyList()
    }
    override fun findUniqueDatesBeforeCursor(
        cursor: LocalDate,
        pageable: Pageable
    ): List<LocalDate> {
        val uniqueDates = table.filter {
            it.topic.appliedAt!! < cursor
        }.map { it.topic.appliedAt!! }.distinct().sortedByDescending { it }

        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(uniqueDates.size)

        return if (offset < uniqueDates.size) uniqueDates.subList(offset, toIndex) else emptyList()
    }

    override fun findByDateAndType(
        date: LocalDate,
        type: BoardType,
        pageable: Pageable
    ): List<Board> {
        val boards = table.filter {
            it.topic.appliedAt!! == date && it.boardType == type
        }.sortedByDescending { it.id }

        val pageSize = pageable.pageSize
        val offset = pageable.offset.toInt()
        val toIndex = (offset + pageSize).coerceAtMost(boards.size)

        return if (offset < boards.size) boards.subList(offset, toIndex) else emptyList()
    }

    fun clear() {
        table.clear()
    }
}